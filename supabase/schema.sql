create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at=now(); return new; end $$;

create or replace function public.recalculate_inventory_stock() returns trigger
language plpgsql security definer set search_path=public
as $$
declare v_inventory bigint;
begin
  v_inventory=coalesce(new.inventory_id,old.inventory_id);
  update public.inventory_items i
  set current_stock=coalesce((select sum(c.quantity_remaining) from public.containers c where c.inventory_id=v_inventory and c.status='ACTIVE'),0), updated_at=now()
  where i.id=v_inventory;
  return coalesce(new,old);
end $$;

create or replace function public.audit_change() returns trigger
language plpgsql security definer set search_path=public
as $$
declare r jsonb; v_lab uuid; v_id text;
begin
  r=case when tg_op='DELETE' then to_jsonb(old) else to_jsonb(new) end;
  v_lab=(r->>'lab_id')::uuid;
  v_id=r->>'id';
  insert into public.audit_logs(lab_id,action,entity_type,entity_id,actor_id,actor_email,old_data,new_data)
  values(v_lab,tg_op,tg_table_name,v_id,(select auth.uid()),(select auth.jwt()->>'email'),case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) end,case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) end);
  return coalesce(new,old);
end $$;

-- updated_at triggers
DO $$ declare t text; begin
  foreach t in array array['labs','profiles','inventory_items','containers','vendors','procurement_requests','procurement_items'] loop
    execute format('drop trigger if exists trg_touch_%I on public.%I',t,t);
    execute format('create trigger trg_touch_%I before update on public.%I for each row execute function public.touch_updated_at()',t,t);
  end loop;
end $$;

drop trigger if exists trg_container_stock on public.containers;
create trigger trg_container_stock after insert or update or delete on public.containers for each row execute function public.recalculate_inventory_stock();

