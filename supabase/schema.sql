-- Atomic stock consumption with FEFO behavior.
create or replace function public.consume_inventory(p_inventory_id bigint,p_quantity numeric,p_project text default null,p_purpose text default null,p_container_id bigint default null)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare v_lab uuid=(select public.current_lab_id()); v_item public.inventory_items%rowtype; v_total numeric; v_left numeric=p_quantity; c record; v_take numeric; v_parts jsonb='[]'::jsonb;
begin
  if v_lab is null then raise exception 'Not authenticated'; end if;
  if p_quantity<=0 then raise exception 'Quantity must be positive'; end if;
  select * into v_item from public.inventory_items where id=p_inventory_id and lab_id=v_lab;
  if not found then raise exception 'Inventory item not found'; end if;
  select coalesce(sum(quantity_remaining),0) into v_total from public.containers where inventory_id=p_inventory_id and lab_id=v_lab and status='ACTIVE' and quantity_remaining>0 and (p_container_id is null or id=p_container_id);
  if v_total<p_quantity then raise exception 'Insufficient stock'; end if;
  for c in select * from public.containers where inventory_id=p_inventory_id and lab_id=v_lab and status='ACTIVE' and quantity_remaining>0 and (p_container_id is null or id=p_container_id) order by expiry_date nulls last, created_at for update loop
    exit when v_left<=0;
    v_take=least(v_left,c.quantity_remaining);
    update public.containers set quantity_remaining=quantity_remaining-v_take,status=case when quantity_remaining-v_take<=0 then 'DEPLETED' else status end where id=c.id;
    v_left=v_left-v_take;
    v_parts=v_parts||jsonb_build_array(jsonb_build_object('container_id',c.id,'container_code',c.container_code,'quantity',v_take));
  end loop;
  insert into public.usage_logs(lab_id,inventory_id,item_name,quantity,unit,project,purpose,parts,used_by)
  values(v_lab,v_item.id,v_item.name,p_quantity,v_item.unit,coalesce(p_project,v_item.project,''),coalesce(p_purpose,''),v_parts,(select auth.uid()));
  return v_parts;
end $$;

-- Admin-only stocktake adjustment. Positive differences create a traceable adjustment container;
-- negative differences deplete existing containers FEFO without creating a scientific usage entry.
create or replace function public.adjust_inventory(p_inventory_id bigint,p_new_stock numeric,p_reason text default '')
returns numeric language plpgsql security definer set search_path=public
as $$
declare v_lab uuid=(select public.current_lab_id()); v_item public.inventory_items%rowtype; v_delta numeric; v_left numeric; c record; v_take numeric;
begin
  if not (select public.is_admin()) then raise exception 'Admin required'; end if;
  if p_new_stock<0 then raise exception 'Stock cannot be negative'; end if;
  select * into v_item from public.inventory_items where id=p_inventory_id and lab_id=v_lab for update;
  if not found then raise exception 'Inventory item not found'; end if;
  v_delta=p_new_stock-v_item.current_stock;
  if v_delta>0 then
    insert into public.containers(lab_id,inventory_id,quantity_initial,quantity_remaining,unit,lot_number,received_date,expiry_date,storage,status)
    values(v_lab,v_item.id,v_delta,v_delta,v_item.unit,'ADJUSTMENT-'||to_char(now(),'YYYYMMDD-HH24MISS'),current_date,v_item.expiry_date,v_item.storage,'ACTIVE');
  elsif v_delta<0 then
    v_left=-v_delta;
    for c in select * from public.containers where inventory_id=v_item.id and lab_id=v_lab and status='ACTIVE' and quantity_remaining>0 order by expiry_date nulls last, created_at for update loop
      exit when v_left<=0; v_take=least(v_left,c.quantity_remaining);
      update public.containers set quantity_remaining=quantity_remaining-v_take,status=case when quantity_remaining-v_take<=0 then 'DEPLETED' else status end where id=c.id;
      v_left=v_left-v_take;
    end loop;
  end if;
  insert into public.audit_logs(lab_id,action,entity_type,entity_id,actor_id,actor_email,new_data)
  values(v_lab,'STOCK_ADJUSTMENT','inventory_items',v_item.id::text,(select auth.uid()),(select auth.jwt()->>'email'),jsonb_build_object('new_stock',p_new_stock,'reason',p_reason));
  return p_new_stock;
end $$;

create or replace function public.place_order(p_request_id bigint,p_vendor_id bigint,p_expected_date date,p_ordered_total numeric)
returns public.procurement_requests language plpgsql security definer set search_path=public
as $$
declare v_lab uuid=(select public.current_lab_id()); r public.procurement_requests%rowtype; v_prefix text; v_po text;
begin
  if not (select public.is_admin()) then raise exception 'Admin required'; end if;
  select * into r from public.procurement_requests where id=p_request_id and lab_id=v_lab for update;
  if not found then raise exception 'Request not found'; end if;
  if r.status<>'Requested' then raise exception 'Request is not in Requested status'; end if;
  if not exists(select 1 from public.vendors where id=p_vendor_id and lab_id=v_lab) then raise exception 'Vendor not found'; end if;
  select po_prefix into v_prefix from public.labs where id=v_lab;
  v_po=coalesce(r.po_number,coalesce(v_prefix,'LABB-PO')||'-'||extract(year from current_date)::int||'-'||lpad(nextval('public.po_number_seq')::text,5,'0'));
  update public.procurement_requests set vendor_id=p_vendor_id,expected_date=p_expected_date,ordered_total=coalesce(p_ordered_total,0),po_number=v_po,status='Ordered' where id=p_request_id returning * into r;
  return r;
end $$;

create or replace function public.receive_procurement(p_request_id bigint,p_lines jsonb)
returns public.procurement_requests language plpgsql security definer set search_path=public
as $$
declare v_lab uuid=(select public.current_lab_id()); r public.procurement_requests%rowtype; z jsonb; pi public.procurement_items%rowtype; inv public.inventory_items%rowtype; v_qty numeric;
begin
  if not (select public.is_admin()) then raise exception 'Admin required'; end if;
  select * into r from public.procurement_requests where id=p_request_id and lab_id=v_lab for update;
  if not found then raise exception 'Request not found'; end if;
  if r.status not in ('Ordered','Partial','Delayed') then raise exception 'Request is not receivable'; end if;
  for z in select * from jsonb_array_elements(p_lines) loop
    select * into pi from public.procurement_items where id=(z->>'procurement_item_id')::bigint and request_id=p_request_id and lab_id=v_lab for update;
    if not found then raise exception 'Procurement item not found'; end if;
    v_qty=least(coalesce((z->>'qty')::numeric,0),pi.quantity-pi.received_quantity);
    if v_qty<=0 then continue; end if;
    select * into inv from public.inventory_items where id=pi.inventory_id and lab_id=v_lab;
    update public.procurement_items set received_quantity=received_quantity+v_qty where id=pi.id;
    insert into public.containers(lab_id,inventory_id,quantity_initial,quantity_remaining,unit,lot_number,received_date,expiry_date,storage,status,source_request_id)
    values(v_lab,inv.id,v_qty,v_qty,inv.unit,coalesce(z->>'lot_number',''),current_date,coalesce(nullif(z->>'expiry_date','')::date,inv.expiry_date),inv.storage,'ACTIVE',p_request_id);
  end loop;
  if not exists(select 1 from public.procurement_items where request_id=p_request_id and received_quantity<quantity) then
    update public.procurement_requests set status='Delivered' where id=p_request_id returning * into r;
  else
    update public.procurement_requests set status='Partial' where id=p_request_id returning * into r;
  end if;
  return r;
end $$;

