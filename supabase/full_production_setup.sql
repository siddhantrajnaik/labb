-- Triggers & Functions
create or replace function public.touch_updated_at() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  new.updated_at = now();
  return new;
end $$;

create or replace function public.audit_change() returns trigger
language plpgsql security definer set search_path=public as $$
declare
  v_lab uuid;
  v_actor uuid := auth.uid();
  v_target_id text;
  v_details jsonb;
begin
  if TG_OP = 'DELETE' then
    v_lab := old.lab_id;
    v_target_id := old.id::text;
    v_details := to_jsonb(old);
  else
    v_lab := new.lab_id;
    v_target_id := new.id::text;
    v_details := to_jsonb(new);
  end if;

  insert into public.audit_logs (lab_id, actor_id, action, target_type, target_id, details)
  values (v_lab, v_actor, TG_OP, TG_TABLE_NAME, v_target_id, v_details);

  return coalesce(new, old);
end $$;

create or replace function public.recalculate_inventory_stock() returns trigger
language plpgsql security definer set search_path=public as $$
declare
  v_inv_id bigint := coalesce(new.inventory_id, old.inventory_id);
  v_lab_id uuid := coalesce(new.lab_id, old.lab_id);
begin
  update public.inventory_items
  set current_stock = coalesce((
    select sum(remaining_quantity) from public.containers
    where inventory_id = v_inv_id and is_depleted = false
  ), 0),
  updated_at = now()
  where id = v_inv_id and lab_id = v_lab_id;
  return coalesce(new, old);
end $$;

