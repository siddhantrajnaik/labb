-- Core Tables
create table if not exists public.labs (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  address text not null default '',
  po_prefix text not null default 'LABB-PO',
  expiry_notice_days integer not null default 90 check (expiry_notice_days between 1 and 3650),
  reorder_horizon_days integer not null default 30 check (reorder_horizon_days between 1 and 3650),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  lab_id uuid not null references public.labs(id) on delete cascade,
  display_name text not null,
  email text,
  role text not null default 'member' check (role in ('admin','member')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists profiles_lab_idx on public.profiles(lab_id);

-- Helper functions
create or replace function public.current_lab_id() returns uuid
language sql stable security definer set search_path=public
as $$ select lab_id from public.profiles where id=(select auth.uid()) and active=true $$;

create or replace function public.current_role() returns text
language sql stable security definer set search_path=public
as $$ select role from public.profiles where id=(select auth.uid()) and active=true $$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path=public
as $$ select coalesce((select public.current_role())='admin',false) $$;

revoke all on function public.current_lab_id() from public;
revoke all on function public.current_role() from public;
revoke all on function public.is_admin() from public;
grant execute on function public.current_lab_id() to authenticated;
grant execute on function public.current_role() to authenticated;
grant execute on function public.is_admin() to authenticated;

